import math as _math


def s_pair(radius, sweep, climb, sign):
    """S-пара: дуга туда-дуга обратно. Курс возвращается к исходному,
    ряд сдвигается вбок на 2R(1-cos teta) в сторону первой дуги."""
    return [
        ("a", radius, sweep, climb * 0.5, sign),
        ("a", radius, sweep, climb * 0.5, -sign),
    ]


def _pair_shift(radius, sweep):
    return 2.0 * radius * (1.0 - _math.cos(_math.radians(sweep)))


def flow_row(items, start_sign, climb, march=+1):
    """Ряд «дуг»: чередующиеся S-пары и короткие прямые. climb — СУММАРНЫЙ
    подъём ряда, он распределяется пропорционально длине элементов. В конце —
    компенсирующая S-пара, гасящая накопившийся боковой дрейф (пары разного
    радиуса не сокращаются в ноль точно)."""
    total = 0.0
    for item in items:
        if item[0] == "s":
            total += item[1]
        else:
            total += 2.0 * item[1] * _math.sin(_math.radians(item[2]))
    rate = climb / max(total, 1.0)
    segs = []
    sign = start_sign
    drift = 0.0
    for item in items:
        if item[0] == "s":
            segs.append(("s", item[1], item[1] * rate))
        else:
            radius, sweep = item[1], item[2]
            advance = 2.0 * radius * _math.sin(_math.radians(sweep))
            segs += s_pair(radius, sweep, advance * rate, sign)
            drift += sign * march * _pair_shift(radius, sweep)
            sign = -sign
    if abs(drift) > 1.0:
        sweep = 25.0
        radius = abs(drift) / (2.0 * (1.0 - _math.cos(_math.radians(sweep))))
        radius = min(max(radius, 45.0), 320.0)
        comp_sign = -1 if drift * march > 0 else 1
        segs += s_pair(radius, sweep, climb * 0.1, comp_sign)
    return segs


def turnaround(climb, sign):
    """Разворот 180° «дугой» (не шпилька): шаг ряда 2*52 = 104 м."""
    return [("a", 52.0, 180.0, climb, sign)]


