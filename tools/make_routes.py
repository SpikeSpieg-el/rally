def serpentine(levels, radius, traverse, climbs):
    """Лестница шпилек с ЧЕРЕДОВАНИЕМ направления: витки строго параллельны.

    Шпилька ровно 180°, направление чередуется (правая-левая-правая...),
    траверсы прямые. Тогда витки ложатся лестницей с шагом 2*radius (~32 м),
    все шпильки выпирают наружу (вниз по склону) — как настоящая горная
    дорога. Однонаправленные шпильки НЕ работают: вторая шпилька возвращает
    траверс точно на предыдущий виток (проверено на практике).
    """
    segs = []
    for i in range(levels):
        direction = +1 if i % 2 == 0 else -1
        segs.append(("a", radius, 180.0, climbs[i][0], direction))
        segs.append(("s", traverse[i], climbs[i][1]))
    return segs


