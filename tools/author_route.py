CURVE_UID = "uid://cnkrnb4gwuihg"
MIN_CLEARANCE = 34.0        # мин. зазор между витками трассы (м)


def main():
    pts, length = kit.build_intent(SEGS, max_grade_deg=5.2)
    ctrl = kit.select_controls(pts, max_gap=44.0, min_gap=10.0, turn_trigger_deg=8.0)
    kit.write_curve(ctrl, OUT_CURVE, uid=CURVE_UID)
    print("stage_forest (ночной лес)")
    print("  длина замысла    %.0f м" % length)
    print("  контрольных      %d" % len(ctrl))
    ok = kit.verify(OUT_CURVE, pts, min_clearance=MIN_CLEARANCE)
    kit.render(pts, "/tmp/route_forest.png")
    if not ok:
        raise SystemExit("ПРОВЕРКА НЕ ПРОШЛА: правь SEGS или параметры kit")
    print("written " + OUT_CURVE)


if __name__ == "__main__":
    main()
